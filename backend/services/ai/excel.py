"""Excel export for the AI agent: the editable skill file + the workbook builder.

The skill file (services/ai/skills/excel.md) is read on every call so the user can edit it without a
restart. Its ```json block is the house style (validated, bad values fall back to defaults); the rest
is guidance text for the model. Formatting is applied here in code, never left to the model.
"""
import io
import json
import re
from datetime import date, datetime
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

SKILL_FILE = Path(__file__).parent / "skills" / "excel.md"
MAX_SHEETS = 5
MAX_ROWS = 2000
MAX_COLUMNS = 30
MAX_BYTES = 5 * 1024 * 1024
XLSX_MIME = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"

_HEX = re.compile(r"^[0-9A-Fa-f]{6}$")
DEFAULT_STYLE = {
    "headerFill": "1F4E79",
    "headerFont": "FFFFFF",
    "titleSize": 14,
    "moneyFormat": '"RM"#,##0.00',
    "dateFormat": "yyyy-mm-dd",
    "freezeHeader": True,
    "autoFilter": True,
    "totalsRow": True,
    "maxColumnWidth": 50,
    "footer": "Generated by AI Treasurer on {date}",
    "aiNote": "Prepared by AI - check the figures before using them.",
}
_VALID = {
    "headerFill": lambda v: isinstance(v, str) and bool(_HEX.match(v)),
    "headerFont": lambda v: isinstance(v, str) and bool(_HEX.match(v)),
    "titleSize": lambda v: isinstance(v, int) and not isinstance(v, bool) and 8 <= v <= 36,
    "moneyFormat": lambda v: isinstance(v, str) and 0 < len(v) <= 60,
    "dateFormat": lambda v: isinstance(v, str) and 0 < len(v) <= 30,
    "freezeHeader": lambda v: isinstance(v, bool),
    "autoFilter": lambda v: isinstance(v, bool),
    "totalsRow": lambda v: isinstance(v, bool),
    "maxColumnWidth": lambda v: isinstance(v, int) and not isinstance(v, bool) and 10 <= v <= 120,
    "footer": lambda v: isinstance(v, str) and len(v) <= 200,
    "aiNote": lambda v: isinstance(v, str) and len(v) <= 200,
}


def _read_skill(path: Path = SKILL_FILE) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as e:
        print(f"excel skill: cannot read {path} ({e}); using defaults")
        return ""


def load_style(path: Path = SKILL_FILE) -> dict:
    """House style from the skill file's ```json block, every value validated against the defaults."""
    style = dict(DEFAULT_STYLE)
    match = re.search(r"```json\s*(\{.*?\})\s*```", _read_skill(path), re.S)
    if not match:
        return style
    try:
        given = json.loads(match.group(1))
    except json.JSONDecodeError as e:
        print(f"excel skill: style block is not valid JSON ({e}); using defaults")
        return style
    for key, value in (given if isinstance(given, dict) else {}).items():
        if key not in _VALID:
            continue  # unknown keys are ignored
        if _VALID[key](value):
            style[key] = value
        else:
            print(f"excel skill: invalid value for {key!r}: {value!r}; using {DEFAULT_STYLE[key]!r}")
    return style


def load_guidance(path: Path = SKILL_FILE) -> str:
    """The skill text for the model: everything except the style block."""
    return re.sub(r"```json\s*\{.*?\}\s*```", "", _read_skill(path), count=1, flags=re.S).strip()


def safe_filename(title: str) -> str:
    name = re.sub(r"[^\w\s.-]", "", title or "").strip()[:80].strip(" .") or "Spreadsheet"
    return f"{name}.xlsx"


def _sheet_title(name: str, used: set) -> str:
    base = re.sub(r"[\[\]:*?/\\]", "", name or "").strip()[:31] or "Sheet"
    title, n = base, 2
    while title.lower() in used:
        suffix = f" ({n})"
        title, n = base[: 31 - len(suffix)] + suffix, n + 1
    used.add(title.lower())
    return title


def _as_date(value):
    if isinstance(value, (date, datetime)):
        return value
    if isinstance(value, str):
        try:
            return date.fromisoformat(value.strip()[:10])
        except ValueError:
            return value
    return value


def _as_number(value):
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return value
    if isinstance(value, str):
        try:
            return float(value.replace(",", "").replace("RM", "").strip())
        except ValueError:
            return value
    return value


def _write_text(cell, value):
    """Text is always stored as text: a value like '=HYPERLINK(...)' must never become a live formula."""
    cell.value = value
    if isinstance(value, str):
        cell.data_type = "s"


def build_workbook(title: str, sheets: list[dict], style: dict | None = None, ai_made: bool = False) -> bytes:
    """sheets = [{name, columns: [str], rows: [[value]], money_columns: [str], date_columns: [str]}].
    Returns .xlsx bytes in the house style. Raises ValueError when a limit is exceeded."""
    style = style or load_style()
    if not sheets:
        raise ValueError("The spreadsheet needs at least one sheet.")
    if len(sheets) > MAX_SHEETS:
        raise ValueError(f"At most {MAX_SHEETS} sheets.")

    wb = Workbook()
    wb.remove(wb.active)
    used_names: set = set()
    header_fill = PatternFill("solid", fgColor=style["headerFill"])
    header_font = Font(bold=True, color=style["headerFont"])
    note = style["aiNote"] if ai_made else style["footer"].replace("{date}", date.today().isoformat())

    for spec in sheets:
        columns = [str(c) for c in (spec.get("columns") or [])][:MAX_COLUMNS + 1]
        rows = spec.get("rows") or []
        if not columns:
            raise ValueError("Every sheet needs at least one column.")
        if len(columns) > MAX_COLUMNS:
            raise ValueError(f"At most {MAX_COLUMNS} columns per sheet.")
        if len(rows) > MAX_ROWS:
            raise ValueError(f"At most {MAX_ROWS} rows per sheet.")
        money = {i for i, c in enumerate(columns) if c in set(spec.get("money_columns") or [])}
        dates = {i for i, c in enumerate(columns) if c in set(spec.get("date_columns") or [])}

        ws = wb.create_sheet(_sheet_title(spec.get("name") or title, used_names))
        _write_text(ws.cell(row=1, column=1), title)
        ws.cell(row=1, column=1).font = Font(bold=True, size=style["titleSize"])
        _write_text(ws.cell(row=2, column=1), note)
        ws.cell(row=2, column=1).font = Font(italic=True, color="7F7F7F")
        header_row = 4
        widths = [len(c) for c in columns]

        for ci, name in enumerate(columns, start=1):
            cell = ws.cell(row=header_row, column=ci)
            _write_text(cell, name)
            cell.fill, cell.font = header_fill, header_font
            cell.alignment = Alignment(vertical="center")

        for ri, row in enumerate(rows, start=header_row + 1):
            values = list(row)[: len(columns)] if isinstance(row, (list, tuple)) else [row]
            for ci, value in enumerate(values):
                if value is None or value == "":
                    continue
                cell = ws.cell(row=ri, column=ci + 1)
                if ci in money:
                    value = _as_number(value)
                    if isinstance(value, (int, float)) and not isinstance(value, bool):
                        cell.value = value
                        cell.number_format = style["moneyFormat"]
                    else:
                        _write_text(cell, str(value))
                elif ci in dates:
                    value = _as_date(value)
                    if isinstance(value, (date, datetime)):
                        cell.value = value
                        cell.number_format = style["dateFormat"]
                    else:
                        _write_text(cell, str(value))
                elif isinstance(value, (int, float)) and not isinstance(value, bool):
                    cell.value = value
                else:
                    _write_text(cell, str(value))
                shown = f"RM{value:,.2f}" if ci in money and isinstance(value, (int, float)) and not isinstance(value, bool) else str(value)
                widths[ci] = max(widths[ci], len(shown))

        last_row = header_row + len(rows)
        if style["totalsRow"] and money and rows:
            total_row = last_row + 1
            label_col = next(i for i in range(len(columns)) if i not in money) if len(money) < len(columns) else None
            if label_col is not None:
                _write_text(ws.cell(row=total_row, column=label_col + 1), "Total")
                ws.cell(row=total_row, column=label_col + 1).font = Font(bold=True)
            for ci in money:
                letter = get_column_letter(ci + 1)
                cell = ws.cell(row=total_row, column=ci + 1)
                cell.value = f"=SUM({letter}{header_row + 1}:{letter}{last_row})"
                cell.number_format = style["moneyFormat"]
                cell.font = Font(bold=True)

        for ci, width in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(ci)].width = min(max(width + 2, 8), style["maxColumnWidth"])
        if style["freezeHeader"]:
            ws.freeze_panes = ws.cell(row=header_row + 1, column=1)
        if style["autoFilter"] and rows:
            ws.auto_filter.ref = f"A{header_row}:{get_column_letter(len(columns))}{last_row}"

    buffer = io.BytesIO()
    wb.save(buffer)
    data = buffer.getvalue()
    if len(data) > MAX_BYTES:
        raise ValueError("The spreadsheet is too large (over 5 MB).")
    return data


if __name__ == "__main__":
    import tempfile
    from openpyxl import load_workbook

    # style: valid file, bad values fall back, missing block = defaults, edits picked up without re-import
    with tempfile.TemporaryDirectory() as tmp:
        p = Path(tmp) / "excel.md"
        p.write_text('intro\n```json\n{"headerFill": "FF0000", "titleSize": "big", "nope": 1}\n```\nGuide text', encoding="utf-8")
        s = load_style(p)
        assert s["headerFill"] == "FF0000" and s["titleSize"] == DEFAULT_STYLE["titleSize"] and "nope" not in s
        assert load_guidance(p) == "intro\n\nGuide text"
        p.write_text("no block here", encoding="utf-8")
        assert load_style(p) == DEFAULT_STYLE
        p.write_text('```json\n{"headerFill": "00FF00"}\n```', encoding="utf-8")
        assert load_style(p)["headerFill"] == "00FF00"
    assert load_style()["moneyFormat"]  # the real skill file parses

    data = build_workbook("Games receipts", [{
        "name": "Receipts", "columns": ["Date", "Receipt", "Amount"],
        "rows": [["2026-01-02", "=HYPERLINK(\"http://x\")", 12.5], ["2026-01-03", "Lunch", "1,000.50"]],
        "money_columns": ["Amount"], "date_columns": ["Date"],
    }], style=DEFAULT_STYLE)
    ws = load_workbook(io.BytesIO(data))["Receipts"]
    assert ws["A1"].value == "Games receipts" and ws["A4"].value == "Date" and ws["A4"].font.bold
    assert ws["B5"].value.startswith("=HYPERLINK") and ws["B5"].data_type == "s"  # stays text, not a formula
    assert isinstance(ws["A5"].value, datetime) and ws["A5"].number_format == "yyyy-mm-dd"
    assert ws["C6"].value == 1000.5 and ws["C6"].number_format == '"RM"#,##0.00'
    assert ws["C7"].value == "=SUM(C5:C6)" and ws["A7"].value == "Total"
    assert ws.freeze_panes == "A5" and ws.auto_filter.ref == "A4:C6"
    for bad in ([], [{"name": "x", "columns": []}], [{"columns": ["a"], "rows": [[1]] * (MAX_ROWS + 1)}]):
        try:
            build_workbook("t", bad, style=DEFAULT_STYLE)
            raise AssertionError("limit not enforced")
        except ValueError:
            pass
    assert safe_filename('Q3: "budget"/plan') == "Q3 budgetplan.xlsx" and safe_filename("") == "Spreadsheet.xlsx"
    print("excel self-check OK")
